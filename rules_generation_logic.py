# MOCK GENERATIONS & PROOF
# ==========================================

def generated_text_alpha(state: TrackState, chip: Chip, append_element: Callable):
    start_pos = chip.position + 2.0
    for i in range(3):
        pos = start_pos + (i * 5.0)
        append_element('A', pos)

def generated_text_beta(state: TrackState, chip: Chip, append_element: Callable):
    start_pos = chip.position + 1.0
    for i in range(2):
        pos = start_pos + (i * 2.0)
        append_element('X', pos)

if __name__ == "__main__":
    manager = TrackManager()

    print("--- 1. First Rule Text (Alpha) ---")
    manager.switch_rules_text("Text_Alpha", generated_text_alpha)
    manager.print_track()

    print("\n--- 2. Machine Switches Text (Beta) ---")
    manager.switch_rules_text("Text_Beta", generated_text_beta)
    manager.print_track()